import assert from 'node:assert/strict';
import {SkillDatabase} from '../../js/skill-database.js';
import {UnitRuntimeEngine} from '../../js/unit-runtime-engine.js';
const rule={label:'森靈之魂',max:30,initial:0,naturalRecovery:0,collectionRadius:2,regenerationRounds:3};
const character={id:'ophi',passives:['FOREST_SOUL_RESONANCE'],attributes:{int:20,wil:20},resourceRules:{mana:true,forestSoul:rule}};
const unit={id:'test-ophi',alive:true,resources:{},character};
const skill=SkillDatabase.get('ophi_forest_entangle');
assert.equal(skill.manaCost,22);
assert.deepEqual(skill.forestSoulCast,{cost:6,mpFallback:true});
UnitRuntimeEngine.syncResources(unit,{initialize:true});
UnitRuntimeEngine.syncMana(unit,{initialize:true});
const originalMana=unit.mana;
assert.equal(UnitRuntimeEngine.resourceLabel(unit,skill),'MP 22');
UnitRuntimeEngine.changeResource(unit,'forestSoul',6);
assert.equal(UnitRuntimeEngine.resourceLabel(unit,skill),'森靈之魂 6');
assert.equal(UnitRuntimeEngine.resourceFor(unit,skill).cost,0);
const spent=UnitRuntimeEngine.consumeSkill(unit,skill);
assert.equal(spent.cost,0);
assert.equal(spent.resources.forestSoul.cost,6);
assert.equal(unit.resources.forestSoul.value,0);
assert.equal(unit.mana,originalMana);
UnitRuntimeEngine.changeResource(unit,'forestSoul',5);
assert.equal(UnitRuntimeEngine.resourceLabel(unit,skill),'MP 22');
assert.equal(UnitRuntimeEngine.consumeSkill(unit,skill).cost,22);
assert.equal(unit.resources.forestSoul.value,5,'MP fallback leaves partial soul intact');
unit.mana=0;
assert.equal(UnitRuntimeEngine.canUseSkill(unit,skill),false);
UnitRuntimeEngine.changeResource(unit,'forestSoul',1);
assert.equal(UnitRuntimeEngine.canUseSkill(unit,skill),true);
assert.equal(UnitRuntimeEngine.consumeSkill(unit,skill).resources.forestSoul.cost,6);
assert.equal(unit.mana,0);
assert.equal(SkillDatabase.get('ophi_healing_song').forestSoulCast.cost,6);
console.log('Ophi entangle soul priority, MP fallback and independent resource payment passed');

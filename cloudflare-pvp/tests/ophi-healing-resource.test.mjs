import assert from 'node:assert/strict';
import {SkillDatabase} from '../../js/skill-database.js';
import {UnitRuntimeEngine} from '../../js/unit-runtime-engine.js';
const rule={label:'森靈之魂',max:30,initial:0,naturalRecovery:0,collectionRadius:2,regenerationRounds:3};
const unit={id:'test-ophi',alive:true,resources:{},character:{id:'ophi',passives:['FOREST_SOUL_RESONANCE'],attributes:{int:20,wil:20},resourceRules:{mana:true,forestSoul:rule}}};
const skill=SkillDatabase.get('ophi_healing_song');
UnitRuntimeEngine.syncResources(unit,{initialize:true});
UnitRuntimeEngine.syncMana(unit,{initialize:true});
assert.equal(UnitRuntimeEngine.resourceLabel(unit,skill),'MP 24');
assert.equal(UnitRuntimeEngine.canUseSkill(unit,skill),true);
const manaBefore=unit.mana;
UnitRuntimeEngine.changeResource(unit,'forestSoul',6);
assert.equal(UnitRuntimeEngine.resourceLabel(unit,skill),'森靈之魂 6');
assert.equal(UnitRuntimeEngine.resourceFor(unit,skill).cost,0);
let result=UnitRuntimeEngine.consumeSkill(unit,skill);
assert.equal(result.cost,0);
assert.equal(result.resources.forestSoul.cost,6);
assert.equal(unit.mana,manaBefore);
assert.equal(unit.resources.forestSoul.value,0);
assert.equal(UnitRuntimeEngine.resourceLabel(unit,skill),'MP 24');
result=UnitRuntimeEngine.consumeSkill(unit,skill);
assert.equal(result.cost,24);
assert.equal(unit.mana,manaBefore-24);
UnitRuntimeEngine.changeResource(unit,'forestSoul',4);
assert.equal(UnitRuntimeEngine.resourceLabel(unit,skill),'MP 24');
unit.mana=0;
assert.equal(UnitRuntimeEngine.canUseSkill(unit,skill),false);
assert.equal(UnitRuntimeEngine.consumeSkill(unit,skill),null);
UnitRuntimeEngine.changeResource(unit,'forestSoul',2);
assert.equal(UnitRuntimeEngine.canUseSkill(unit,skill),true);
assert.equal(UnitRuntimeEngine.consumeSkill(unit,skill).resources.forestSoul.cost,6);
console.log('Ophi heal soul preferred and MP fallback: all assertions passed');

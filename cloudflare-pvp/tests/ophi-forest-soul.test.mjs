import assert from 'node:assert/strict';
import {SkillDatabase} from '../../js/skill-database.js';
import {UnitRuntimeEngine} from '../../js/unit-runtime-engine.js';
import {TacticalEngine} from '../../js/tactical-engine.js';
import {VfxDatabase} from '../../js/vfx-database.js';
const rule={label:'森靈之魂',max:30,initial:0,naturalRecovery:0,collectionRadius:2,regenerationRounds:3};
const makeUnit=(id,x,y)=>({id,team:'P',x,y,alive:true,mana:100,maxMana:100,resources:{},character:{id:'ophi',attributes:{int:20,wil:20},combat:{matk:88},passives:['FOREST_SOUL_RESONANCE'],weapons:{elven_bow:{weaponKind:'BOW',attackType:'SHOT'}},resourceRules:{forestSoul:rule,mana:true}}});
const tree=(id,x,y,health=72)=>({id,x,y,type:'TREE',maxDurability:72,durability:health});
const bush=(id,x,y)=>({id,x,y,type:'BUSH',maxDurability:24,durability:24});
const ophi=makeUnit('ophi-test',1,1);
const forest={objects:[tree('a',0,0),bush('b',1,0),tree('c',3,1,36),tree('far',10,10)]};
assert.equal(UnitRuntimeEngine.forestSoulValue(ophi),0);
assert.equal(UnitRuntimeEngine.syncForestSouls(forest,[ophi],1,{emit:false}).length,3);
assert.equal(UnitRuntimeEngine.forestSoulValue(ophi),5.5);
assert.equal(forest.objects[0].durability,72,'collect must never damage a tree');
assert.equal(forest.objects[1].durability,24);
assert.equal(forest.objects[3].ophiForestSoul.amount,3,'far soul remains on source');
assert.equal(UnitRuntimeEngine.syncForestSouls(forest,[ophi],1,{emit:false}).length,0,'no duplicate on round 1');
assert.equal(UnitRuntimeEngine.syncForestSouls(forest,[ophi],2,{emit:false}).length,0,'regen is not a player/enemy phase');
assert.equal(UnitRuntimeEngine.syncForestSouls(forest,[ophi],3,{emit:false}).length,0,'cooldown 3 full rounds');
assert.equal(UnitRuntimeEngine.syncForestSouls(forest,[ophi],4,{emit:false}).length,3,'tree regrows on round 4');
assert.equal(UnitRuntimeEngine.forestSoulValue(ophi),11);
// Full resources are held until an explicit wrath cast; no automatic attack spending.
UnitRuntimeEngine.changeResource(ophi,'forestSoul',19);
assert.equal(UnitRuntimeEngine.forestSoulFull(ophi),true);
assert.equal(UnitRuntimeEngine.forestSoulMagicPower(ophi,SkillDatabase.get('ophi_triple_shot')),.45);
assert.equal(UnitRuntimeEngine.forestSoulMagicPower(ophi,SkillDatabase.get('ophi_forest_wrath')),0);
const wrath=SkillDatabase.get('ophi_forest_wrath');
const scaled=UnitRuntimeEngine.applyResourceScaling(ophi,wrath);
assert.equal(Math.round(scaled.power*1000)/1000,Math.round((wrath.power*(1+30/33))*1000)/1000);
const spent=UnitRuntimeEngine.consumeSkill(ophi,scaled);
assert.equal(spent.resources.forestSoul.cost,30);
assert.equal(UnitRuntimeEngine.forestSoulFull(ophi),false);
assert.equal(UnitRuntimeEngine.forestSoulMagicPower(ophi,SkillDatabase.get('ophi_elven_shot')),0);
assert.equal(UnitRuntimeEngine.applyResourceScaling(ophi,wrath).power,wrath.power,'zero soul spell works');
assert.equal(VfxDatabase.roleFor('nature-growth','ophi_triple_shot'),'TRIPLE');
assert.equal(VfxDatabase.roleFor('nature-growth','ophi_forest_wrath'),'WRATH');
assert.equal(SkillDatabase.getPassive('FOREST_SOUL_RESONANCE').id,'FOREST_SOUL_RESONANCE');
assert.equal(SkillDatabase.get('ophi_triple_shot').hitCount,3);
assert.equal(SkillDatabase.get('ophi_multishot').targetType,'AOE');
assert.equal(SkillDatabase.get('ophi_backstep_shot').backstep.distance,1);
// Shared official geometry is a wedge, not a circular radius around the cursor.
const map={tiles:Array.from({length:11*11},(_,i)=>({x:i%11,y:Math.floor(i/11),elevation:0,terrain:'PLAIN'}))};
const wedge=TacticalEngine.fanTiles(map,{x:5,y:5},{x:7,y:5},{length:4});
assert(wedge.some(t=>t.x===9&&t.y===7));
assert(!wedge.some(t=>t.x===5&&t.y===8));
assert(!wedge.some(t=>t.x===4&&t.y===5));
assert.equal(new Set(wedge.map(t=>t.x+','+t.y)).size,wedge.length);
console.log('Ophi forest soul + hero skills: all assertions passed');
